fun main() {
    var i = 200
    println("Integer value i = " + i)

    var j : Int = 100
    println("Integer value j = " + j)

    var k : Float = 1.5f
    println("Float value k = " + k)

    var l : Char = 'M'
    println("Character value l = " + l)

    var m : String = "Maharsh"
    println("String value m = " + m)

    var n : Boolean = false
    println("Boolean value n = " + n)

    var o : Double = 13.06
    println("Double value o = " + o)

    var p : Long = 130605
    println("Long value p = " + p)

    var q : Short = -17
    println("Short value q = " + q)

    var r : Byte = 127
    println("Byte value r = " + r)

    val z = 20000
    println("Constant integer value z = " + z)
}
